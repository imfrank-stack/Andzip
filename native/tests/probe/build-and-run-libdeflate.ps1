<#
.SYNOPSIS
  Build and run the stage P2-b libdeflate spike: is a swapped-in Deflate coder fast enough
  to clear the plan's 2x gate, and what does its API shape cost?

.DESCRIPTION
  P2-b (section 6.2 of the compression-speedup plan doc) says: vendor libdeflate, wrap it
  as the engine's Deflate coder, and keep it only if ZIP/Deflate throughput reaches 2x the
  P0 baseline without losing more than 2% ratio. Vendoring first and finding the number
  later is the expensive order, so this spike asks the two cheap questions before anything
  is copied into third_party/:

    1. throughput and ratio of libdeflate itself on the same corpus the engine rows were
       measured on (128 MiB of "mixed", generated by tests/perf/bench.ps1);
    2. whether the library offers an API shape that a ZIP entry coder needs at all -- that
       part is read off the public header, not measured (see docs/perf-p2b-libdeflate.md).

  The checkout lives in build/libdeflate-spike, which is gitignored: nothing here can write
  into third_party/ or into any product build tree, and the repository keeps no copy of the
  library. Only the public header is used; the library is compiled from its own sources.

  Requires the same toolset as the native build (cl.exe via vcvars64) and git on PATH.
  On this machine git needs a proxy to reach github; pass it with -Proxy.

.EXAMPLE
  powershell -File native/tests/probe/build-and-run-libdeflate.ps1 -DataFile $env:TEMP\andzip-perf-tiers\mixed-128.bin

.EXAMPLE
  powershell -File native/tests/probe/build-and-run-libdeflate.ps1 -Proxy http://127.0.0.1:2080 -Out docs/perf-libdeflate.tsv

.NOTES
  Keep this file pure ASCII (every .ps1 in this repo does).
#>
param(
  [string]$DataFile = '',
  [string]$Tag = 'v1.26',
  [string]$Proxy = '',
  [string]$Out = '',
  [switch]$SkipClone
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 3.0

$nativeRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$repoRoot   = (Resolve-Path (Join-Path $nativeRoot '..')).Path
$spikeRoot  = Join-Path $repoRoot 'build\libdeflate-spike'
$srcRoot    = Join-Path $spikeRoot 'libdeflate'
$outDir     = Join-Path $spikeRoot 'out'

function Find-VsPath {
  $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
  if (-not (Test-Path -LiteralPath $vswhere)) { throw "vswhere not found: $vswhere" }
  $found = (& $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath)
  if (-not $found) { throw 'no Visual Studio with the C++ toolset found' }
  return ($found | Select-Object -First 1)
}

function Import-VcVars([string]$VsPath) {
  $vcvars = Join-Path $VsPath 'VC\Auxiliary\Build\vcvars64.bat'
  if (-not (Test-Path -LiteralPath $vcvars)) { throw "vcvars64.bat not found: $vcvars" }
  $lines = & cmd.exe /d /c "`"$vcvars`" >nul 2>&1 && set"
  foreach ($line in $lines) {
    if ($line -match '^([^=]+)=(.*)$') { [Environment]::SetEnvironmentVariable($matches[1], $matches[2], 'Process') }
  }
  if (-not (Get-Command cl.exe -ErrorAction SilentlyContinue)) { throw 'cl.exe is not on PATH after importing vcvars64' }
}

if (-not $DataFile) {
  $DataFile = Join-Path $env:TEMP 'andzip-perf-tiers\mixed-128.bin'
}
if (-not (Test-Path -LiteralPath $DataFile)) {
  throw "corpus not found: $DataFile (generate it with: powershell -File tests/perf/bench.ps1)"
}

if (-not $SkipClone -and -not (Test-Path -LiteralPath (Join-Path $srcRoot 'libdeflate.h'))) {
  New-Item -ItemType Directory -Path $spikeRoot -Force | Out-Null
  $repo = 'https://github.com/ebiggers/libdeflate.git'
  Write-Output "== clone libdeflate $Tag into $srcRoot =="
  if ($Proxy) {
    & git -c "http.proxy=$Proxy" clone --quiet --depth 1 --branch $Tag $repo $srcRoot
  } else {
    & git clone --quiet --depth 1 --branch $Tag $repo $srcRoot
  }
  if ($LASTEXITCODE -ne 0) { throw "git clone failed (exit $LASTEXITCODE)" }
}
if (-not (Test-Path -LiteralPath (Join-Path $srcRoot 'libdeflate.h'))) {
  throw "no checkout at $srcRoot -- drop -SkipClone or check the tag"
}
$head = (& git -C $srcRoot rev-parse --short HEAD)
Write-Output "checkout: $Tag @ $head"

New-Item -ItemType Directory -Path $outDir -Force | Out-Null
$vsPath = Find-VsPath
Import-VcVars -VsPath $vsPath
$env:VSLANG = '1033'   # English compiler diagnostics; a localized VS writes GBK to the console

# The library is 9 .c files plus the x86 cpu probe; no assembly, no cmake, no generated
# headers, so one cl invocation is the whole build. /O2 matches libdeflate's own release
# flags (CMAKE_C_FLAGS_RELEASE is '-O2 -DNDEBUG').
$sources = @(
  (Join-Path $PSScriptRoot 'libdeflate_spike.c'),
  'lib\deflate_compress.c', 'lib\deflate_decompress.c', 'lib\zlib_compress.c',
  'lib\zlib_decompress.c', 'lib\gzip_compress.c', 'lib\gzip_decompress.c',
  'lib\adler32.c', 'lib\crc32.c', 'lib\utils.c', 'lib\x86\cpu_features.c'
) | ForEach-Object { if ([IO.Path]::IsPathRooted($_)) { $_ } else { Join-Path $srcRoot $_ } }

$exe = Join-Path $outDir 'libdeflate_spike.exe'
# One flat array: a nested array in the argument list reaches cl.exe as a single
# space-joined filename (measured -- C1083 on a path containing every source).
$clArgs = @(
  '/nologo', '/TC', '/O2', '/MD', '/DNDEBUG', '/D_CRT_SECURE_NO_WARNINGS',
  "/I$srcRoot",
  "/Fo:$outDir\"
) + $sources + @(
  '/link', "/OUT:$exe"
)

Write-Output '== compile =='
& cl.exe @clArgs
if ($LASTEXITCODE -ne 0) { throw "cl.exe failed (exit $LASTEXITCODE)" }

Write-Output '== run =='
$name = [IO.Path]::GetFileNameWithoutExtension($DataFile) -replace '-\d+$', ''
$text = & $exe $DataFile $name
if ($LASTEXITCODE -ne 0) { throw "spike failed (exit $LASTEXITCODE)" }
$text | ForEach-Object { Write-Output $_ }

if ($Out) {
  $path = if ([IO.Path]::IsPathRooted($Out)) { $Out } else { Join-Path $repoRoot $Out }
  Set-Content -LiteralPath $path -Value (($text -join "`r`n") + "`r`n") -Encoding ascii -NoNewline
  Write-Output "  wrote $path"
}
